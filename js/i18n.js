const DICTS = { it, en, de, es, fr };
const DEFAULT_LOCALES = { it: "it-IT", en: "en-GB", de: "de-DE", es: "es-ES", fr: "fr-FR" };
const LANG_KEY = "fw.lang";

const isLang = (value) => typeof value === "string" && Object.hasOwn(LANGS, value);

function detectLang() {
  try {
    const saved = globalThis.window?.localStorage.getItem(LANG_KEY);
    if (isLang(saved)) return saved;
  } catch {
    // storage non disponibile
  }
  const nav = globalThis.navigator;
  for (const l of nav?.languages ?? [nav?.language ?? ""]) {
    const code = l.slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "en";
}

export let lang = detectLang();

export function setLang(next) {
  if (!isLang(next)) return;
  lang = next;
  if (globalThis.document) document.documentElement.lang = next;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    // storage non disponibile: vale solo per questa visita
  }
}

/** Locale BCP-47 per numeri e date: tiene la regione del browser se corrisponde alla lingua scelta. */
export function locale() {
  const nav = globalThis.navigator?.language ?? "";
  return nav.slice(0, 2).toLowerCase() === lang && nav.length > 2 ? nav : DEFAULT_LOCALES[lang];
}

/** Testo tradotto; i parametri {nome} vengono sostituiti così come sono (possono contenere HTML già sicuro). */
export function t(key, params) {
  let s = DICTS[lang][key] ?? it[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const countLabel = (n) => (n === 1 ? t("expenseOne") : t("expenseMany", { n }));
